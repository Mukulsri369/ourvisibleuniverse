export type GalaxyLevel = 1 | 2 | 3 | 4;

export type GalaxyDistanceTier =
  "local_group" | "nearby_groups" | "virgo_cluster" | "distant_clusters" | "high_redshift";

export type NamedGalaxy = {
  name: string;
  type: string;
  // galactic coords
  l: number; // deg
  b: number; // deg
  distance: number; // light-years
  // Rendered disk diameter in ly
  size: number;
  color: string;
  inclination?: number; // deg, tilt of disk from face-on
  posAngle?: number; // deg, orientation of major axis in sky
};

export interface ObservationalGalaxy extends NamedGalaxy {
  id: string; // Canonical identifier e.g. "MESSIER-031"
  preferredName: string; // Authoritative NED designation
  aliases: string[]; // Cross-catalog designations
  ra: number; // J2000 Right Ascension in decimal degrees
  dec: number; // J2000 Declination in decimal degrees
  redshift: number; // Heliocentric / CMB redshift z
  redshiftMethod?: "spectroscopic" | "photometric" | "optical" | "hi_21cm" | "ned_consensus";
  redshiftUncertainty?: number;
  radialVelocityKmS?: number; // Radial velocity in km/s (negative = blueshifted/approaching)
  independentDistanceLy?: number; // Redshift-independent distance in ly
  independentDistanceMpc?: number; // In megaparsecs
  independentDistanceMethod?:
    | "Cepheid"
    | "TRGB"
    | "SN Ia"
    | "Tully-Fisher"
    | "SBF"
    | "Eclipsing Binary"
    | "Cosmological"
    | "cepheid_variable"
    | "detached_eclipsing_binaries";
  distanceUncertaintyLy?: number;
  independentDistanceUncertaintyLy?: number;
  morphologyClass: string; // de Vaucouleurs / Hubble type e.g. "SA(s)b", "SB(s)m", "E0"
  morphologyCategory?: string; // "spiral" | "elliptical" | "irregular" | "lenticular"
  angularDiameterArcmin: { major: number; minor: number };
  apparentMagnitude?: { band: string; value: number };
  photometry?: Record<string, number>;
  hostGroup?: string; // e.g. "Local Group", "Virgo Cluster", "M81 Group"
  constellation?: string;
  observationSource: string; // "NED", "NED-D", "SDSS", "HST", "JWST", "2MASS"
  bibcode?: string;
  uncertaintyNotes?: string;
  level: GalaxyLevel; // Hierarchical rendering level (1: point, 2: disc/icon, 3: photorealistic, 4: visitable 3D)
  renderLevel?: GalaxyLevel; // Alias for level
  isDetailedReconstruction?: boolean; // True for visitable 3D reconstruction models
  distanceTier: GalaxyDistanceTier;
}

