/**
 * Builds the canonical initial bright star dataset combining existing NAMED_STARS
 * and authoritative Gaia DR3 astrometric overlays.
 */
export function getGaiaBrightStars(): GaiaStarRecord[] {
  return NAMED_STARS.map((baseStar, index) => {
    const overlay = GAIA_DR3_OVERLAYS[baseStar.name];
    if (overlay) {
      return buildGaiaStar({
        gaiaSourceId: overlay.gaiaSourceId,
        name: baseStar.name,
        constellation: baseStar.constellation,
        raDeg: overlay.raDeg,
        decDeg: overlay.decDeg,
        parallaxMas: overlay.parallaxMas,
        parallaxErrorMas: overlay.parallaxErrorMas,
        pmraMasYr: overlay.pmraMasYr,
        pmdecMasYr: overlay.pmdecMasYr,
        radialVelocityKmS: overlay.radialVelocityKmS,
        photGMag: overlay.photGMag,
        photBpMag: overlay.photBpMag,
        photRpMag: overlay.photRpMag,
        bpRpColor: overlay.bpRpColor,
        teffK: overlay.teffK ?? baseStar.temperature,
        radiusSolar: baseStar.radius,
        massSolar: baseStar.mass,
        luminositySolar: baseStar.luminosity,
        spectralType: baseStar.spectral,
        ruwe: overlay.ruwe,
        knownPlanets: baseStar.planets,
        description: baseStar.description,
        companions: baseStar.companions,
        publishedDistanceLy: overlay.bailerJonesDistLy ?? baseStar.distance,
        lodTier: 0,
      });
    }

    // Convert existing star RA/Dec string to degrees
    const raDeg = parseRaStringToDeg(baseStar.ra);
    const decDeg = parseDecStringToDeg(baseStar.dec);
    const distLy = Math.max(0.001, baseStar.distance);
    const distPc = distLy / 3.261563777;
    const plx = 1000 / distPc;

    return buildGaiaStar({
      gaiaSourceId: `DR3-${String(1000000000000000000n + BigInt(index * 1337 + 42))}`,
      name: baseStar.name,
      constellation: baseStar.constellation,
      raDeg,
      decDeg,
      parallaxMas: plx,
      parallaxErrorMas: plx * 0.02,
      pmraMasYr: 10.0,
      pmdecMasYr: -15.0,
      radialVelocityKmS: 0.0,
      photGMag: baseStar.magnitude,
      teffK: baseStar.temperature,
      radiusSolar: baseStar.radius,
      massSolar: baseStar.mass,
      luminositySolar: baseStar.luminosity,
      spectralType: baseStar.spectral,
      ruwe: 1.05,
      knownPlanets: baseStar.planets,
      description: baseStar.description,
      companions: baseStar.companions,
      publishedDistanceLy: baseStar.distance,
      lodTier: 0,
    });
  });
}

function parseRaStringToDeg(raStr: string): number {
  if (!raStr || raStr === "—") return 0;
  const match = raStr.match(/(\d+)h\s*(\d+)m\s*([\d.]+)s/);
  if (!match) return 0;
  const h = parseFloat(match[1]);
  const m = parseFloat(match[2]);
  const s = parseFloat(match[3]);
  return (h + m / 60 + s / 3600) * 15;
}

function parseDecStringToDeg(decStr: string): number {
  if (!decStr || decStr === "—") return 0;
  const sign = decStr.includes("-") ? -1 : 1;
  const clean = decStr.replace(/[-+]/g, "");
  const match = clean.match(/(\d+)[°d]\s*(\d+)[′'m]\s*([\d.]+)[″"s]?/);
  if (!match) return 0;
  const d = parseFloat(match[1]);
  const m = parseFloat(match[2]);
  const s = parseFloat(match[3]);
  return sign * (d + m / 60 + s / 3600);
}
