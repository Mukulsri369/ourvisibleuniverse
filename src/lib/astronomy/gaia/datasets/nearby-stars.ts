/**
 * Returns canonical high-precision Gaia DR3 solar neighborhood stars.
 */
export function getGaiaNearbyStars(): GaiaStarRecord[] {
  return GAIA_NEARBY_CATALOG_DATA.map((s) =>
    buildGaiaStar({
      gaiaSourceId: s.id,
      name: s.name,
      constellation: s.con,
      raDeg: s.ra,
      decDeg: s.dec,
      parallaxMas: s.plx,
      parallaxErrorMas: s.plxErr,
      pmraMasYr: s.pmra,
      pmdecMasYr: s.pmdec,
      radialVelocityKmS: s.vrad,
      photGMag: s.g,
      photBpMag: s.bp,
      photRpMag: s.rp,
      teffK: s.teff,
      spectralType: s.sp,
      ruwe: 1.05,
      lodTier: 1,
    }),
  );
}
